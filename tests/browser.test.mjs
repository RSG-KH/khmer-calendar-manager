    assert.equal(exported.events.find(e => e.id === 'test-history').originalDate, '1920-09-24');
    assert.equal(exported.overrides.length, 1);
    assert.equal(exported.holidayCalendars[0].holidays[0].dates[0], '2026-07-31');
