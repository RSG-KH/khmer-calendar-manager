    await page.getByRole('button', { name: 'Apply import', exact: true }).click();

    await page.locator('article').filter({ hasText: 'Test lunar event' }).getByRole('button', { name: 'Edit', exact: true }).click();
    await openSection(page, 'Change dates for a specific year');
    await page.getByRole('button', { name: 'Change 2026 dates', exact: true }).click();
    await page.getByLabel('Anchor year', { exact: true }).fill('2026');
    await page.getByLabel('Supporting source', { exact: true }).selectOption(source.id);
    await page.getByLabel(/^Replacement dates/).fill('2026-07-31');
    await page.getByLabel('Reason', { exact: true }).fill('Synthetic browser-test correction');
    await page.getByRole('dialog', { name: 'Change event dates', exact: true }).getByRole('button', { name: 'Add to draft', exact: true }).click();
    await page.getByRole('dialog', { name: 'Edit event', exact: true }).getByRole('button', { name: 'Cancel', exact: true }).click();
    await navigate(page, 'Review & save');
    await page.getByLabel('Change note', { exact: true }).fill('Browser workflow test');
    await page.getByRole('button', { name: 'Save changes', exact: true }).click();
    await page.getByText('Saved · revision 1', { exact: true }).waitFor();
    await navigate(page, 'Export');
    await page.getByRole('button', { name: 'Prepare export', exact: true }).click();
    const [dataDownload] = await Promise.all([page.waitForEvent('download'), page.getByRole('button', { name: 'Download data JSON', exact: true }).click()]);
    await dataDownload.saveAs(join(output, 'data.json'));
